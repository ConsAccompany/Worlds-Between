# Build the self-contained female complete-exploration pilot package (UNAPPROVED, opt-in only).
# Copies the authored sources under game/ without changing art or cadence:
#   * EAST v03 / WEST v01 / NORTH v06 model scripts: byte-for-byte copies except the one SOURCE line of EAST/WEST,
#     which is rewritten from res://../outputs/... to the copied PXO under res://assets/fexp/ (checked below).
#   * SOUTH v10r1: the pure inner classes (IM, PartCompositor, Loco, Loco7, Comp9, Comp10, Loco10, Loco10r1) of the
#     test-only SceneTree chain v06 -> v07 -> v09 -> v10 -> v10r1, concatenated verbatim into one RefCounted script.
#   * the 48 idle-four phase PNGs (4 directions x 12 phases) and the two out-of-project PXOs.
# Every source and copy is hashed (sha256-text-lf-v1 for text: CRLF -> LF only; sha256-bytes for PNG/PXO).
# Usage: python -I <this file> <checkout root>
import hashlib, json, os, re, shutil, sys

STAMP = "20261019-184500-f2c0a7e1"
P = "rpg-2-star-ocean-the-second_female-complete-explore_"
root = os.path.abspath(sys.argv[1])
tools = os.path.join(root, "tools")
game = os.path.join(root, "game")
sdir = os.path.join(game, "scripts", "fexp")
adir = os.path.join(game, "assets", "fexp")
ddir = os.path.join(game, "data", "fexp")
for d in (sdir, adir, ddir):
    os.makedirs(d, exist_ok=True)


def text_sha(path):
    data = open(path, "rb").read().replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()


def bytes_sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def rel(path):
    return os.path.relpath(path, root).replace("\\", "/")


entries = []
MODELS = {
    "east": ("rpg-2-star-ocean-the-second_female-east_run-stop-source_unapproved-v03_20261018-193030-48da69c1.gd", True),
    "west": ("rpg-2-star-ocean-the-second_female-west_run-stop-source_unapproved-v01_20261018-181150-a94f021c.gd", True),
    "north": ("rpg-2-star-ocean-the-second_female-north_run-stop-source_unapproved-v06_20261019-001844-7759f49b.gd", False),
}
models_out = {}
for direction, (name, rewrite) in MODELS.items():
    src = os.path.join(tools, name)
    text = open(src, encoding="utf-8").read().replace("\r\n", "\n")
    lines = text.split("\n")
    changed = []
    if rewrite:
        for i, line in enumerate(lines):
            m = re.match(r'^const SOURCE := "res://\.\./outputs/([^"]+)/([^"/]+\.pxo)"$', line)
            if m:
                pxo_src = os.path.join(root, "outputs", m.group(1), m.group(2))
                pxo_dst = os.path.join(adir, m.group(2))
                shutil.copyfile(pxo_src, pxo_dst)
                assert bytes_sha(pxo_src) == bytes_sha(pxo_dst)
                entries.append({"role": direction + "-pxo", "source": rel(pxo_src), "copy": rel(pxo_dst),
                                "sha256_bytes": bytes_sha(pxo_dst)})
                lines[i] = 'const SOURCE := "res://assets/fexp/%s"' % m.group(2)
                changed.append(i + 1)
        assert len(changed) == 1, (direction, changed)
    assert "res://../" not in "\n".join(lines), direction
    out_name = P + "%s-model_runtime-copy-v01_%s.gd" % (direction, STAMP)
    out = os.path.join(sdir, out_name)
    open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    # Only the SOURCE line may differ.
    a = text.split("\n")
    b = open(out, encoding="utf-8").read().split("\n")
    assert len(a) == len(b) and [i + 1 for i in range(len(a)) if a[i] != b[i]] == changed
    entries.append({"role": direction + "-model", "source": rel(src), "source_sha256_text_lf_v1": text_sha(src),
                    "copy": rel(out), "copy_sha256_text_lf_v1": text_sha(out), "changed_lines": changed})
    models_out[direction] = "res://scripts/fexp/" + out_name

CHAIN = [
    ("rpg-2-star-ocean-the-second_protagonist-female_south-run-v06-godot-capture_m8-w09_20261017-211600-ff47ce98.gd", ["IM", "PartCompositor", "Loco"]),
    ("rpg-2-star-ocean-the-second_protagonist-female_south-run-v07-godot-capture_m8-w10_20261018-082500-8770ac39.gd", ["Loco7"]),
    ("rpg-2-star-ocean-the-second_female-south-run-v09-godot-capture_m8-w12_20261018-133700-4d620536.gd", ["Comp9"]),
    ("rpg-2-star-ocean-the-second_female-south-run-v10-godot-capture_m8-w13_20261018-143213-ed496e32.gd", ["Comp10", "Loco10"]),
    ("rpg-2-star-ocean-the-second_female-south-run-v10r1-godot-capture_m8-w14_20261018-142136-249dbf66.gd", ["Loco10r1"]),
]
south_name = P + "south-model_extracted-v01_%s.gd" % STAMP
parts = ["extends RefCounted\n",
         "# GENERATED by %s (do not edit): the pure SOUTH v10r1 inner classes of the test-only SceneTree capture chain,\n"
         "# copied verbatim in chain order. No class line or body line is changed. Unapproved; opt-in pilot only.\n"
         % os.path.basename(__file__)]
for name, classes in CHAIN:
    src = os.path.join(tools, name)
    lines = open(src, encoding="utf-8").read().replace("\r\n", "\n").split("\n")
    found = []
    i = 0
    while i < len(lines):
        m = re.match(r"^class (\w+)", lines[i])
        if m:
            j = i + 1
            while j < len(lines) and (lines[j] == "" or lines[j][0] in "\t#"):
                j += 1
            # Trailing blank/comment lines belong to the next top-level item; drop them.
            k = j
            while k > i + 1 and (lines[k - 1] == "" or lines[k - 1].startswith("#")):
                k -= 1
            parts.append("\n\n# ---- from %s ----\n" % name)
            parts.append("\n".join(lines[i:k]) + "\n")
            found.append(m.group(1))
            i = j
        else:
            i += 1
    assert found == classes, (name, found)
    entries.append({"role": "south-chain", "source": rel(src), "source_sha256_text_lf_v1": text_sha(src), "classes": found})
south_out = os.path.join(sdir, south_name)
open(south_out, "w", encoding="utf-8", newline="\n").write("".join(parts))
entries.append({"role": "south-model", "copy": rel(south_out), "copy_sha256_text_lf_v1": text_sha(south_out)})

idle_manifest_path = os.path.join(root, "outputs", "female-idle-four-v01",
                                  "rpg-2-star-ocean-the-second_female-idle-four_direction-manifest_unapproved-v01_20261018-175418-34294d7d.json")
idle_manifest = json.load(open(idle_manifest_path, encoding="utf-8"))
idle = {"cell": idle_manifest["cell"], "pivot": idle_manifest["pivot"], "scale": idle_manifest["scale"],
        "phase_seconds": [p["seconds"] for p in idle_manifest["phases"]], "directions": {}}
entries.append({"role": "idle-manifest", "source": rel(idle_manifest_path), "source_sha256_text_lf_v1": text_sha(idle_manifest_path)})
for direction in ["south", "west", "north", "east"]:
    files = []
    for frame in idle_manifest["directions"][direction]["frames"]:
        src = os.path.join(root, frame["files"]["png"]["file"])
        assert bytes_sha(src) == frame["files"]["png"]["sha256"], src
        dst = os.path.join(adir, os.path.basename(src))
        shutil.copyfile(src, dst)
        assert bytes_sha(dst) == frame["files"]["png"]["sha256"]
        files.append({"file": "res://assets/fexp/" + os.path.basename(src), "sha256": bytes_sha(dst), "source": rel(src)})
    idle["directions"][direction] = files

package = {"schema": "worlds-between.female-complete-explore-package.v1", "approved": False, "runtimeDefault": False,
           "builder": rel(os.path.abspath(__file__)), "builder_sha256_text_lf_v1": text_sha(os.path.abspath(__file__)),
           "hash_normalization": {"text": "sha256-text-lf-v1 (CRLF -> LF only)", "binary": "sha256-bytes"},
           "pivot": [40, 104], "scale": 0.5, "body_logical_px": 48,
           "models": models_out, "south_model": "res://scripts/fexp/" + south_name, "idle": idle, "entries": entries}
out = os.path.join(ddir, P + "package_v01_%s.json" % STAMP)
open(out, "w", encoding="utf-8", newline="\n").write(json.dumps(package, indent=1) + "\n")
print("PACKAGE", rel(out), text_sha(out))
print("FCX_PACKAGE_BUILD_OK")
