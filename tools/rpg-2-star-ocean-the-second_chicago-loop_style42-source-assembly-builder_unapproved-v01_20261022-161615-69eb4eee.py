def defaults_state():
    path = ROOT / DEFAULTS_POLICY
    if not path.exists():
        return {"policy": DEFAULTS_POLICY, "present": False, "note": "not present in this checkout; no game file is edited"}
    text = path.read_text(encoding="utf-8")
    vals = {k: (re.search(r"const %s := (true|false)" % k, text) or [None, None])[1] for k in DEFAULT_SWITCHES}
    if any(v != "false" for v in vals.values()):
        raise SystemExit(f"default switch not false: {vals}")
    return {"policy": DEFAULTS_POLICY, "present": True, "policy_sha256_text_lf": text_sha(path.read_bytes()),
            "switches": {k: False for k in vals}, "edited_by_this_tool": False}


