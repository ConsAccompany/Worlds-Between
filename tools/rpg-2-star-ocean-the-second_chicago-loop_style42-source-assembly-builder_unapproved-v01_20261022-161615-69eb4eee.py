def rgba(data):
    return np.array(Image.open(io.BytesIO(data)).convert("RGBA"))


def nearest_640(ref):
    """NEAREST exact source-pixel sampling: each output pixel copies one reference pixel unchanged."""
    sh, sw = ref.shape[:2]
    sx = (np.arange(W) * 2 + 1) * sw // (2 * W)
    sy = (np.arange(H) * 2 + 1) * sh // (2 * H)
    return ref[sy][:, sx], sx, sy


def parse_gd_props(text):
    rows = re.findall(r'\["([a-z-]+)", Rect2\((\d+), (\d+), (\d+), (\d+)\), ([\d.]+)\]', text.split("const YSORT_PROPS := [")[1].split("\n]")[0])
    return [[r[0], [int(v) for v in r[1:5]], float(r[5])] for r in rows]


def grad(luma):
    return np.abs(np.diff(luma, axis=1, append=luma[:, -1:])) + np.abs(np.diff(luma, axis=0, append=luma[-1:]))


def best_shift(a, b, box, r=4):
    """Pearson correlation of edge maps: v05 region a vs converted reference b moved by (dx, dy) in -r..r."""
    x0, y0, x1, y1 = max(box[0], r), max(box[1], r), min(box[2], W - r), min(box[3], H - r)
    A = a[y0:y1, x0:x1].ravel()
    best, at0 = None, None
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            B = b[y0 + dy:y1 + dy, x0 + dx:x1 + dx].ravel()
            c = float(np.corrcoef(A, B)[0, 1]) if A.std() > 0 and B.std() > 0 else 0.0
            if (dx, dy) == (0, 0):
                at0 = c
            if best is None or c > best[0] + 1e-12:
                best = (c, dx, dy)
    return {"corr_at_0": round(at0, 4), "best_shift": [best[1], best[2]], "best_corr": round(best[0], 4)}


def alignment(conv, v05_flat, props, masks):
    luma = lambda img: img[..., :3].astype(np.float64) @ np.array([0.299, 0.587, 0.114])
    a, b = grad(luma(v05_flat)), grad(luma(conv))
    rows = [{"name": p["name"], **best_shift(a, b, (p["region"][0] - 4, p["region"][1] - 4, p["region"][0] + p["region"][2] + 4,
                                                        p["region"][1] + p["region"][3] + 4))} for p in props]
    dark = [int(y) for y in range(H) if luma(conv[y:y + 1]).mean() > 40]
    return {"method": "Pearson correlation of |dx|+|dy| luma edge maps, v05 composite vs converted reference, integer shifts -4..4 "
                      "(diagnostic only; not a production metric). A non-zero best shift means the generated reference's feature "
                      "is offset from the v05 silhouette, so the plane can carry rim pixels of the wrong surface.",
            "global_rows_62_359": best_shift(a, b, (0, 62, W, H)),
            "top_strip_first_bright_row_reference": dark[0] if dark else None, "top_strip_first_row_v05": 62,
            "props": rows, "props_with_nonzero_best_shift": [r["name"] for r in rows if r["best_shift"] != [0, 0]]}


