def sha(data):
    return hashlib.sha256(data).hexdigest()


def text_sha(data):
    return sha(data.replace(b"\r\n", b"\n"))


def lp(path):
    return Path("\\\\?\\" + str(path.resolve()))


def read_input(key):
    path, algo, want = INPUTS[key]
    data = lp(ROOT / path).read_bytes()
    got = text_sha(data) if algo == "sha256-text-lf-v1" else sha(data)
    if got != want:
        raise SystemExit(f"input hash mismatch: {path}: {got} != {want}")
    return data


def load_v05():
    """The v05 author module, imported unchanged, for its walk mask, PNG, ORA and PXO writers. Its globals are
    redirected to this candidate (ROOT, output dirs, layers, archive time); v05's build() is never called."""
    read_input("v05-author")
    spec = spec_from_file_location("chicago_author_v05_for_style42", ROOT / INPUTS["v05-author"][0])
    mod = module_from_spec(spec)
    spec.loader.exec_module(mod)
    mod.ROOT, mod.OUT, mod.RUNTIME = ROOT, OUT, RUNTIME
    mod.PREFIX, mod.LAYERS, mod.GUIDE, mod.ZIP_TIME = SUBJECT, LAYERS, GUIDE, ZIP_TIME
    return mod


