def foot_x(p):
    """Sole-anchor x and lift for the near leg at phase p (far leg uses p + 6)."""
    p %= N
    if p <= 6:
        return 44 + 24 - 48 * (p / 6), 0.0
    s = (p - 6) / 6
    return 44 - 24 + 48 * (0.5 - 0.5 * math.cos(math.pi * s)), LIFT * math.sin(math.pi * s)


def lum(c): return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def ramp(layer, rows, pred):
    px = layer[rows[0]:rows[1]][layer[rows[0]:rows[1], :, 3] > 0][:, :3].astype(int)
    px = px[[pred(c) for c in px]]
    vals, cnt = np.unique(px, axis=0, return_counts=True)
    vals = vals[cnt >= 2]; vals = vals[np.argsort([lum(v) for v in vals])]
    pick = lambda q: tuple(int(x) for x in vals[min(len(vals) - 1, int(q * (len(vals) - 1)))])
    return [pick(0.0), pick(0.3), pick(0.6), pick(0.9)]   # outline, dark, mid, light (actual source colours)


def solve_knee(hip, ank, facing):
    dx, dy = ank[0] - hip[0], ank[1] - hip[1]; d = math.hypot(dx, dy)
    d = min(d, 2 * BONE - 0.01); a = d / 2; h = math.sqrt(max(0.0, BONE * BONE - a * a))
    mx, my = hip[0] + dx / 2, hip[1] + dy / 2
    nx, ny = -dy / math.hypot(dx, dy), dx / math.hypot(dx, dy)
    if nx * facing < 0: nx, ny = -nx, -ny             # knee bends toward facing, never hyperextends
    return (mx + nx * h, my + ny * h)


def capsule(mask_shade, a, b, w0, w1, facing):
    """Tapered segment a->b: inside if distance <= width/2; shade by side (front lit, back dark)."""
    ax, ay = a; bx, by = b; vx, vy = bx - ax, by - ay; L2 = vx * vx + vy * vy or 1.0
    for y in range(max(0, int(min(ay, by) - 6)), min(H, int(max(ay, by) + 7))):
        for x in range(max(0, int(min(ax, bx) - 6)), min(W, int(max(ax, bx) + 7))):
            u = max(0.0, min(1.0, ((x - ax) * vx + (y - ay) * vy) / L2))
            qx, qy = ax + u * vx - x, ay + u * vy - y
            r = (w0 + (w1 - w0) * u) / 2
            dist = math.hypot(qx, qy)
            if dist <= r:
                side = (-qx) * facing / max(r, 0.5)          # +1 front edge, -1 back edge
                sh = 3 if side > 0.45 else (1 if side < -0.35 else 2)
                if mask_shade[y, x] == 0 or sh > mask_shade[y, x]: mask_shade[y, x] = sh


SRC = {}
PAL = None


def _src_rows(layer, y0, y1):
    """Per source row: (centre x, half width) of the opaque leg run in the idle generated-base leg layer."""
    out = {}
    for y in range(y0, y1 + 1):
        xs = np.nonzero(layer[y, :, 3] > 0)[0]
        if len(xs): out[y] = ((xs.min() + xs.max()) / 2.0, max(1.0, (xs.max() - xs.min() + 1) / 2.0))
    return out


def _darker(rgb):
    """Far leg: nearest actual source-palette colour to 78 % value."""
    t = np.array(rgb, float) * 0.78
    return tuple(int(v) for v in PAL[((PAL - t) ** 2).sum(1).argmin()])


def paint_leg(hip, foot, lift, facing, trouser, boot, far):
    """Art pose guide: near-straight tapered leg, texture-mapped from the generated base's own leg pixels;
    original boot pixels (bottom 10 rows of the idle leg layer) placed by opaque-sole midpoint."""
    key = "far" if far else "near"; src = SRC[key]
    a = src[..., 3] > 0; ys = np.nonzero(a.any(1))[0]; sole_src = int(ys[-1])
    bt0 = sole_src - 9
    bxs = np.nonzero(a[sole_src])[0]; bmid = (bxs.min() + bxs.max()) / 2.0
    dx_b = int(round(foot - bmid)); dy_b = int(round(SOLE - lift)) - sole_src
    out = np.zeros((H, W, 4), np.uint8)
    rows = _src_rows(src, 74, bt0 + 1)
    top_c = rows[min(rows)][0]; bot_c = rows[max(rows)][0]
    ank = (bot_c + dx_b, bt0 + dy_b + 1)                    # boot shaft top, in destination space
    # knee guide: stance = 2..4 px forward of the hip-ankle midpoint; swing = forward + up with lift
    mx, my = (hip[0] + ank[0]) / 2.0, (hip[1] + ank[1]) / 2.0
    k = (2 + round(2 * (1 - min(1.0, abs(foot - 44) / 24.0)))) if lift == 0 else 3 + lift
    knee = (mx + k * facing, my - (lift * 0.5))
    src_y0, src_y1 = min(rows), max(rows); src_ym = (src_y0 + src_y1) / 2.0
    for (p0, p1, sy0, sy1) in ((hip, knee, src_y0, src_ym), (knee, ank, src_ym, src_y1)):
        vx, vy = p1[0] - p0[0], p1[1] - p0[1]; L = math.hypot(vx, vy) or 1.0
        nx, ny = vy / L, -vx / L
        for y in range(max(0, int(min(p0[1], p1[1])) - 6), min(SOLE + 1, int(max(p0[1], p1[1])) + 7)):
            for x in range(max(0, int(min(p0[0], p1[0])) - 7), min(W, int(max(p0[0], p1[0])) + 8)):
                u = ((x - p0[0]) * vx + (y - p0[1]) * vy) / (L * L)
                if u < -0.05 or u > 1.05: continue
                u = min(1.0, max(0.0, u))
                sy = int(round(sy0 + u * (sy1 - sy0)))
                sy = min(rows, key=lambda r: abs(r - sy)) if sy not in rows else sy
                cx, hw = rows[sy]
                s = -((x - p0[0]) * nx + (y - p0[1]) * ny) * facing   # signed offset across the leg
                sx = int(round(cx + s))
                if abs(s) <= hw + 0.25 and 0 <= sx < W and src[sy, sx, 3]:
                    out[y, x] = src[sy, sx]
    # original boot pixels
    for y in range(bt0, sole_src + 1):
        for x in np.nonzero(a[y])[0]:
            ty, tx = y + dy_b, x + dx_b
            if 0 <= ty <= SOLE and 0 < tx < W - 1: out[ty, tx] = src[y, x]
    if far:
        m = out[..., 3] > 0
        for (yy, xx) in zip(*np.nonzero(m)): out[yy, xx, :3] = _darker(tuple(out[yy, xx, :3]))
    out[SOLE + 1:] = 0
    return out, knee, ank


def sole_anchor(layer):
    a = layer[..., 3] > 0; yb = int(np.nonzero(a.any(1))[0][-1]); xs = np.nonzero(a[yb])[0]
    return [round(float(xs.min() + xs.max()) / 2, 1), yb, int(xs.min()), int(xs.max())]


